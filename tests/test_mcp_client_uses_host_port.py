# tests/test_mcp_client_uses_host_port.py
"""Pins for the MCP stdio spawn: its permission grain, and its DEFERRED migration.

Two separate things are pinned here.

1. Permission grain (DONE).  Tool classes generated by
   ``tools/mcp_manager.create_tool_class`` for a *stdio* MCP server declare
   ``["mcp:connect"]`` -- the same grain ``MCPServerConnect`` uses, because a
   stdio MCP server is an executable launched on the host.  Classes generated for
   an HTTP/SSE server keep declaring ``["network:outbound"]``.  The declaration
   lands on the generated model as the ``required_categories`` ClassVar, so the
   inherited ``ToolBase.get_required_categories`` (what the gate calls, see
   ``agent/core/tool_executor.py``) surfaces it on a real instance.

2. Host execution (DEFERRED, deliberately NOT migrated).  ``tools/mcp_client.py``
   still imports ``subprocess`` and ``StdioMCPClient.start()`` still spawns the
   MCP server itself with::

       self.process = subprocess.Popen([self.command] + self.args, ...)

   That is an unaudited host launch which bypasses the
   ``thoughtmachine/host_port.py`` chokepoint.  The migration is blocked on the
   *asynchronous* port primitive: an MCP stdio child is long-lived (its
   stdin/stdout stay open for the whole session), so it needs ``host_run_async``
   handing back a ``HostRunHandle`` -- and both are signature-only stubs that
   raise ``NotImplementedError`` today.  The deferral is recorded in a comment at
   the Popen site; these tests pin that comment (and its markers) *and* pin that
   the ``subprocess`` import and the ``Popen`` call are still there, so the
   migration can be neither half-done nor silently forgotten.

Nothing here spawns a process, opens a socket or touches the network: the
clients are constructed but never started, and the generated tool classes are
only introspected and instantiated for their categories.
"""

from __future__ import annotations

import ast
import inspect
import subprocess
import textwrap

import pytest

from tools import mcp_client
from tools.base import ToolBase
from tools.mcp_client import create_mcp_client
from tools.mcp_manager import create_tool_class


# ---------------------------------------------------------------------------
# helpers
# ---------------------------------------------------------------------------

_TOOL_DEF = {
    "name": "lookup",
    "description": "Look up a thing.",
    "inputSchema": {
        "type": "object",
        "properties": {"query": {"type": "string"}},
        "required": ["query"],
    },
}

_SERVER_URL = "https://mcp.example.invalid/rpc"


def _stdio_client():
    """A real (never started) stdio client -- no subprocess is spawned."""
    return create_mcp_client("stdio", command="fake-mcp-server", args=["--stdio"])


def _generated_tool_class(client):
    """Run the factory exactly as ``MCPServerManager.start_all`` does."""
    return create_tool_class("deferred", _TOOL_DEF, client)


def _popen_call_in_start():
    """The ``subprocess.Popen`` Call node in ``StdioMCPClient.start``."""
    source = _start_source()
    for node in ast.walk(ast.parse(source)):
        if (
            isinstance(node, ast.Call)
            and isinstance(node.func, ast.Attribute)
            and node.func.attr == "Popen"
            and isinstance(node.func.value, ast.Name)
            and node.func.value.id == "subprocess"
        ):
            return node, source.splitlines()
    pytest.fail("StdioMCPClient.start() no longer calls subprocess.Popen")


def _start_source() -> str:
    lines, _first = inspect.getsourcelines(mcp_client.StdioMCPClient.start)
    return textwrap.dedent("".join(lines))


def _module_tree():
    return ast.parse(inspect.getsource(mcp_client))


def _module_imports(tree) -> list:
    names = []
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            names.extend(alias.name for alias in node.names)
        elif isinstance(node, ast.ImportFrom):
            names.append(node.module or "")
    return names


# ---------------------------------------------------------------------------
# 1. the permission grain of the generated tool classes
# ---------------------------------------------------------------------------


def test_stdio_generated_tool_instance_requires_mcp_connect():
    """A stdio MCP tool must ask the gate for mcp:connect, not network:outbound."""
    tool_class = _generated_tool_class(_stdio_client())

    assert tool_class.required_categories == ["mcp:connect"]
    # The gate calls the classmethod on the class, with the call arguments.
    assert tool_class.get_required_categories({"query": "spam"}) == ["mcp:connect"]

    instance = tool_class(query="spam")
    assert isinstance(instance, ToolBase)
    assert instance.get_required_categories({}) == ["mcp:connect"]
    assert type(instance).get_required_categories() == ["mcp:connect"]


def test_stdio_generated_tool_category_does_not_depend_on_params():
    """The category is static: it is not narrowed or widened by call arguments."""
    tool_class = _generated_tool_class(_stdio_client())

    assert tool_class.get_required_categories({}) == ["mcp:connect"]
    assert tool_class.get_required_categories({"query": "spam"}) == ["mcp:connect"]
    assert tool_class.get_required_categories(None) == ["mcp:connect"]


@pytest.mark.parametrize("transport", ["http", "sse"])
def test_network_generated_tool_instance_still_requires_network_outbound(transport):
    """HTTP/SSE generated tools keep the network:outbound grain."""
    client = create_mcp_client(transport, url=_SERVER_URL)
    tool_class = _generated_tool_class(client)

    assert tool_class.get_required_categories({"query": "spam"}) == ["network:outbound"]

    instance = tool_class(query="spam")
    assert isinstance(instance, ToolBase)
    assert instance.get_required_categories({}) == ["network:outbound"]


def test_stdio_and_network_tools_do_not_share_a_grain():
    stdio_class = _generated_tool_class(_stdio_client())
    http_class = _generated_tool_class(create_mcp_client("http", url=_SERVER_URL))

    stdio_categories = stdio_class.get_required_categories({"query": "spam"})
    http_categories = http_class.get_required_categories({"query": "spam"})

    assert stdio_categories == ["mcp:connect"]
    assert http_categories == ["network:outbound"]
    assert not set(stdio_categories) & set(http_categories)


# ---------------------------------------------------------------------------
# 2. the deferral: the stdio spawn still goes through subprocess.Popen
# ---------------------------------------------------------------------------


def test_deferral_comment_sits_directly_above_the_stdio_popen_call():
    """The deferral note must be a contiguous comment block at the Popen site."""
    popen, lines = _popen_call_in_start()
    first = popen.lineno - 1

    assert lines[first].strip().startswith("self.process = subprocess.Popen(")

    block = []
    index = first - 1
    while index >= 0 and lines[index].lstrip().startswith("#"):
        block.insert(0, lines[index].strip())
        index -= 1

    assert block, "the Popen call must carry a contiguous comment block above it"
    note = " ".join(block)
    assert "DEFERRED" in note
    assert "host_run_async" in note
    assert "HostRunHandle" in note
    assert "NotImplementedError" in note
    assert 'grain="mcp"' in note
    assert "deleted" in note


def test_deferral_markers_exist_in_the_mcp_client_source():
    source = inspect.getsource(mcp_client)

    for marker in ("host_run_async", "HostRunHandle", "NotImplementedError", 'grain="mcp"'):
        assert marker in source, f"deferral marker {marker!r} missing from tools/mcp_client.py"


def test_mcp_client_still_imports_subprocess():
    """The deferral is real: the private-to-module spawn machinery is still here."""
    assert "subprocess" in _module_imports(_module_tree())
    assert mcp_client.subprocess is subprocess


def test_mcp_client_still_calls_subprocess_popen():
    popen, _lines = _popen_call_in_start()
    assert popen.args
    assert callable(mcp_client.subprocess.Popen)


def test_mcp_client_has_not_been_half_migrated_to_the_host_port():
    """No host_run/host_run_async call and no chokepoint import yet."""
    tree = _module_tree()

    called = {
        node.func.id
        for node in ast.walk(tree)
        if isinstance(node, ast.Call) and isinstance(node.func, ast.Name)
    }
    assert "host_run" not in called
    assert "host_run_async" not in called

    imported = _module_imports(tree)
    assert not [name for name in imported if name.startswith("thoughtmachine")]
