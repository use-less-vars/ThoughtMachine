#!/usr/bin/env bash
# scripts/onboard_read.sh -- emit the curated onboarding corpus as one markdown document.
#
#   bash scripts/onboard_read.sh > /tmp/tm_onboarding.md
#
# The document goes to stdout; byte accounting goes to stderr, so redirecting
# stdout gives you a clean, self-contained reading file.
# Every path is checked: a missing file is reported as MISSING, never skipped.
#
# Why excerpts: the full docs/ + KB is ~10 MB and nobody reads it. These ranges
# are the load-bearing first pages; the rest is listed at the end under READ NEXT.
set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT" || { echo "cannot cd to repo root" >&2; exit 1; }

TOTAL=0
COUNT=0
MISSING=0

_header() { printf '\n\n===== %s: %s =====\n\n' "$1" "$2"; }

full() {
  local path="$1" n
  if [ ! -f "$path" ]; then
    _header MISSING "$path"; MISSING=$((MISSING+1)); return
  fi
  n=$(wc -c <"$path")
  _header FILE "$path ($n bytes)"
  cat -- "$path"
  TOTAL=$((TOTAL+n)); COUNT=$((COUNT+1))
}

range() {
  local path="$1" a="$2" b="$3" n
  if [ ! -f "$path" ]; then
    _header MISSING "$path"; MISSING=$((MISSING+1)); return
  fi
  n=$(sed -n "${a},${b}p" -- "$path" | wc -c)
  _header EXCERPT "$path lines ${a}-${b} ($n of $(wc -c <"$path") bytes)"
  sed -n "${a},${b}p" -- "$path"
  TOTAL=$((TOTAL+n)); COUNT=$((COUNT+1))
}

tailn() {
  local path="$1" k="$2" n
  if [ ! -f "$path" ]; then
    _header MISSING "$path"; MISSING=$((MISSING+1)); return
  fi
  n=$(tail -n "$k" -- "$path" | wc -c)
  _header EXCERPT "$path last ${k} lines ($n of $(wc -c <"$path") bytes)"
  tail -n "$k" -- "$path"
  TOTAL=$((TOTAL+n)); COUNT=$((COUNT+1))
}

# --- 1. the map, complete -------------------------------------------------
full docs/ONBOARDING.md
full README.md

# --- 2. the current design of record -------------------------------------
full docs/DESIGN_WORKERS.md

# --- 3. what a worker actually is on this machine ------------------------
# (tracked evidence, not scratch: docs/evidence/process-truth-2026-11-26.md)
full docs/evidence/process-truth-2026-11-26.md

# --- 4. invariants, excerpted --------------------------------------------
range docs/CONTRACTS.md 1 70
range docs/design-pause-reading-mode.md 1 60
range docs/ARCHITECTURE_MACHINE_MODEL.md 1 60

# --- 5. where the operator wants this to go ------------------------------
range .thoughtmachine/knowledge/project/PRIORITIES.md 1 50
range .thoughtmachine/knowledge/personal/lessons_learned.md 1 10
tailn .thoughtmachine/knowledge/personal/lessons_learned.md 45

# --- 6. what the last engineer was handed --------------------------------
range docs/onboarding/NEW_ENGINEER_HANDBOOK.md 1 35

# --- 7. what was deliberately NOT included -------------------------------
printf '\n\n===== READ NEXT (not included above) =====\n\n'
printf '%s\n' \
  'docs/ARCHITECTURE_MACHINE_MODEL.md      what runs where, and what stops it' \
  'docs/CONTRACTS.md                       every invariant, and what pins it' \
  'docs/MACHINE_INVARIANTS_AND_LORE.md     the hard core, operator words' \
  'docs/CONTROL_PLANE.md                   pause / stop / timeout as one plane' \
  'docs/DESIGN_CREDENTIALS.md              one secret, one gate, one record' \
  'docs/DESIGN_RESOURCES.md                ceiling, grant, gate, audit' \
  'docs/DESIGN_TURN_LIFECYCLE.md           the cut, the report, the recovery' \
  'docs/audit-process-mode-observability.md  what a parent can know (323 kB, by section)' \
  'docs/evidence/                          anchored inventories of bindings and ceilings' \
  '.thoughtmachine/knowledge/project/PRIORITIES.md        filed seat by seat' \
  '.thoughtmachine/knowledge/personal/lessons_learned.md  newest first; older is archived' \
  '.thoughtmachine/knowledge/_archive/                   archived KB, if you need history'

printf '\n---\n\n*Corpus generated by scripts/onboard_read.sh. Totals are on stderr.*\n'

printf '\n[onboard] files: %d   missing: %d   total: %d bytes\n' "$COUNT" "$MISSING" "$TOTAL" >&2
[ "$MISSING" -eq 0 ] || printf '[onboard] WARNING: %d path(s) missing above\n' "$MISSING" >&2
exit 0
