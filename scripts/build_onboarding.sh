#!/usr/bin/env bash
# scripts/build_onboarding.sh -- assemble the deterministic KB onboarding bundle.
#
#   ./scripts/build_onboarding.sh          # no arguments: that is the contract
#
# Env:
#   HANDOFF_FILE       router to parse (default: this repo's
#                      .thoughtmachine/knowledge/project/HANDOFF.md)
#   ONBOARDING_BUNDLE  output path (default: /tmp/onboarding_bundle.md)
#
# The bundle is one markdown file: a preamble (what it is, which router, how
# many files), then every file section 2 of the router lists, IN MANIFEST
# ORDER, each introduced by "### File: <repo-relative path> ###" and followed by
# its verbatim contents. The last stdout line reports the bundle's byte size.
#
# Failure modes are hard (non-zero exit, no bundle written): an unparseable
# router, an empty manifest, or a referenced file that exists neither next to
# the router nor at the repo root. A partial bundle is never left behind.
set -euo pipefail

SCRIPT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)
# shellcheck source=lib/kb_manifest.sh
. "$SCRIPT_DIR/lib/kb_manifest.sh"

HANDOFF_FILE=${HANDOFF_FILE:-$(kb_default_handoff "$SCRIPT_DIR")}
OUT=${ONBOARDING_BUNDLE:-/tmp/onboarding_bundle.md}

# Parse the manifest first: kb_entries prints its own diagnostics on stderr and
# returns non-zero for a missing router, a missing section, or an empty list.
entry_list=$(kb_entries "$HANDOFF_FILE")

repo_root=$(kb_repo_root "$HANDOFF_FILE")
handoff_dir=$(cd "$(dirname "$HANDOFF_FILE")" && pwd -P)

count=0
declare -a entries
while IFS= read -r entry; do
  if [ -n "$entry" ]; then
    entries[$count]="$entry"
    count=$((count + 1))
  fi
done <<< "$entry_list"

if [ "$count" -eq 0 ]; then
  printf 'ERROR: %s: no manifest entries parsed; refusing to write an empty bundle.\n' \
    "$HANDOFF_FILE" >&2
  exit 1
fi

tmp="$OUT.tmp.$$"
trap 'rm -f "$tmp"' EXIT HUP INT TERM

{
  printf '# KB onboarding bundle\n\n'
  printf 'Generated by scripts/build_onboarding.sh -- do not edit by hand.\n'
  printf 'Router: %s\n' "$HANDOFF_FILE"
  printf 'Files: %d\n\n' "$count"

  index=0
  while [ "$index" -lt "$count" ]; do
    entry="${entries[$index]}"
    if ! resolved=$(kb_resolve_entry "$HANDOFF_FILE" "$entry"); then
      printf 'ERROR: %s: referenced file "%s" is missing (looked next to the router and at the repo root).\n' \
        "$HANDOFF_FILE" "$entry" >&2
      exit 1
    fi
    printf '### File: %s ###\n\n' "$(kb_rel_path "$repo_root" "$resolved")"
    cat "$resolved"
    # Keep sections separable even when the source file has no final newline.
    if [ -s "$resolved" ] && [ -n "$(tail -c 1 "$resolved")" ]; then
      printf '\n'
    fi
    index=$((index + 1))
  done
} > "$tmp"

mv "$tmp" "$OUT"

# BSD/macOS `wc -c` pads its output with spaces, so trim before reporting.
bytes=$(wc -c < "$OUT" | tr -d '[:space:]')
printf 'Bundle built: %s bytes.\n' "$bytes"
